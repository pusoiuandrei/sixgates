#!/usr/bin/env python3
"""Build the SixGates dashboard data bundle.

Collects data/analyses/**/*.json, validates the minimal fields, writes dashboard/data.js
(window.SIXGATES_DATA = [...]) and dashboard/sixgates_dashboard.html, which is index.html
with data.js inlined so the whole dashboard opens as one file (file://, no server).
Python 3 standard library only.

Usage:
  python3 dashboard/build.py                      rebuild from data/analyses
  python3 dashboard/build.py --add export.json    file an analysis JSON (emitted by a SixGates
                                                  session) as data/analyses/<TICKER>/<date>_v<N>.json,
                                                  then rebuild; repeat --add for several files;
                                                  --force overwrites an existing version
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DASH = ROOT / "dashboard"
DATA_DIR = ROOT / "data" / "analyses"
MARKER = '<script src="data.js"></script>'
NAME_RE = re.compile(r"^\d{4}-\d{2}-\d{2}_v\d+\.json$")


def validate(obj) -> str | None:
    """Return an error message, or None when the minimal contract holds."""
    if not isinstance(obj, dict):
        return "not a JSON object"
    if not str(obj.get("schema_version", "")).startswith("sixgates-analysis"):
        return "schema_version missing or not sixgates-analysis*"
    company, analysis = obj.get("company") or {}, obj.get("analysis") or {}
    if not company.get("ticker"):
        return "company.ticker missing"
    if not analysis.get("date") or analysis.get("version") in (None, ""):
        return "analysis.date or analysis.version missing"
    if not isinstance(obj.get("gates"), list):
        return "gates is not a list"
    return None


def add_file(src: Path, force: bool) -> int:
    """Copy an analysis JSON into data/analyses/<TICKER>/<date>_v<N>.json after validation."""
    try:
        obj = json.loads(src.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        print(f"error: {src}: {exc}", file=sys.stderr)
        return 1
    err = validate(obj)
    if err:
        print(f"error: {src}: {err}", file=sys.stderr)
        return 1
    ticker = str(obj["company"]["ticker"]).upper().strip()
    a = obj["analysis"]
    if not re.match(r"^\d{4}-\d{2}-\d{2}$", str(a["date"])):
        print(f"error: {src}: analysis.date must be AAAA-LL-ZZ, got {a['date']!r}", file=sys.stderr)
        return 1
    dest = DATA_DIR / ticker / f"{a['date']}_v{a['version']}.json"
    if dest.exists() and not force:
        print(f"error: {dest.relative_to(ROOT)} exists; use --force to overwrite or raise analysis.version",
              file=sys.stderr)
        return 1
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(obj, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"added {dest.relative_to(ROOT)}")
    return 0


def main() -> int:
    args = sys.argv[1:]
    force = "--force" in args
    to_add = [Path(args[i + 1]) for i, x in enumerate(args) if x == "--add" and i + 1 < len(args)]
    for src in to_add:
        if add_file(src, force):
            return 1
    analyses, warnings = {}, []
    for path in sorted(DATA_DIR.glob("**/*.json")):
        rel = path.relative_to(ROOT)
        try:
            obj = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            warnings.append(f"skipped {rel}: {exc}")
            continue
        err = validate(obj)
        if err:
            warnings.append(f"skipped {rel}: {err}")
            continue
        ticker, a = obj["company"]["ticker"], obj["analysis"]
        if path.parent.name != ticker:
            warnings.append(f"{rel}: folder name differs from ticker {ticker}")
        if not NAME_RE.match(path.name) or path.name != f"{a['date']}_v{a['version']}.json":
            warnings.append(f"{rel}: expected file name {a['date']}_v{a['version']}.json")
        key = (ticker, str(a["date"]), str(a["version"]))
        if key in analyses:
            warnings.append(f"{rel}: duplicate key {key}, the later file wins")
        analyses[key] = obj

    ordered = [analyses[k] for k in sorted(analyses)]
    # "</" is escaped so the bundle can sit inside an inline <script> element
    payload = json.dumps(ordered, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    js = "/* Generated by dashboard/build.py; do not edit. */\nwindow.SIXGATES_DATA = " + payload + ";\n"
    (DASH / "data.js").write_text(js, encoding="utf-8")

    html = (DASH / "index.html").read_text(encoding="utf-8")
    if MARKER not in html:
        print(f"error: marker {MARKER} not found in index.html", file=sys.stderr)
        return 1
    (DASH / "sixgates_dashboard.html").write_text(html.replace(MARKER, "<script>\n" + js + "</script>", 1), encoding="utf-8")

    tickers = sorted({k[0] for k in analyses})
    print(f"SixGates build: {len(tickers)} companii, {len(ordered)} versiuni")
    for t in tickers:
        for k in sorted(k for k in analyses if k[0] == t):
            o = analyses[k]
            verdicts = ", ".join(f"{g.get('id')}={g.get('verdict')}" for g in o["gates"])
            decision = (o.get("preanalysis") or {}).get("decision")
            print(f"  {t:6} {k[1]} v{k[2]}  pre-analiză={decision}  {verdicts}")
    for w in warnings:
        print("  warning:", w)
    print(f"wrote {(DASH / 'data.js').relative_to(ROOT)} and {(DASH / 'sixgates_dashboard.html').relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
