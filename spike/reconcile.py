def parse_number(text: str, fmt: str) -> float | None:
    """Parse a displayed number according to its inline XBRL format."""
    t = re.sub(r"<[^>]+>", "", text)
    t = html.unescape(t)
    t = "".join(ch for ch in t if ch not in NBSP).strip()
    if t in ("", "-", "\u2014", "\u2013") or "zero" in fmt or "dash" in fmt:
        return 0.0
    neg = t.startswith("(") and t.endswith(")")
    t = t.strip("()")
    if "comma-decimal" in fmt:
        t = t.replace(".", "").replace(",", ".")
    else:
        t = t.replace(",", "")
    try:
        v = float(t)
    except ValueError:
        return None
    return -v if neg else v


def load_ixbrl(raw: str) -> tuple[dict[str, tuple[str, str, bool]], list[dict]]:
    """Contexts (id -> start, end, has_dimensions) and non-fraction facts of an inline XBRL document."""
    contexts: dict[str, tuple[str, str, bool]] = {}
    for m in re.finditer(r"<xbrli:context id=\"([^\"]+)\">(.*?)</xbrli:context>", raw, flags=re.S):
        body = m.group(2)
        start = re.search(r"<xbrli:startDate>([^<]+)<", body)
        end = re.search(r"<xbrli:endDate>([^<]+)<", body)
        instant = re.search(r"<xbrli:instant>([^<]+)<", body)
        has_dim = "<xbrli:segment>" in body or "xbrldi:" in body
        if instant:
            contexts[m.group(1)] = ("", instant.group(1).strip(), has_dim)
        elif start and end:
            contexts[m.group(1)] = (start.group(1).strip(), end.group(1).strip(), has_dim)
    facts: list[dict] = []
    for m in re.finditer(r"<ix:nonFraction\b([^>]*)>(.*?)</ix:nonFraction>", raw, flags=re.S | re.I):
        attrs = dict(re.findall(r"(\w+)=\"([^\"]*)\"", m.group(1)))
        ctx = contexts.get(attrs.get("contextRef", ""))
        if not ctx:
            continue
        v = parse_number(m.group(2), attrs.get("format", ""))
        if v is None:
            continue
        v *= 10 ** int(attrs.get("scale", "0") or 0)
        if attrs.get("sign") == "-":
            v = -v
        facts.append({"name": attrs.get("name", ""), "start": ctx[0], "end": ctx[1], "dim": ctx[2], "value": v,
                      "decimals": attrs.get("decimals", ""), "text": re.sub(r"<[^>]+>", "", m.group(2)).strip()})
    return contexts, facts


def ixbrl_check(facts: list[dict], tags: list[str], end: str, instant: bool, value: float) -> str:
    """Compare an extracted value with the document's own inline fact for the same period."""
    hits = [f for f in facts if f["name"] in tags and f["end"] == end and not f["dim"]
            and (f["start"] == "" if instant else (f["start"] != "" and (date.fromisoformat(f["end"]) - date.fromisoformat(f["start"])).days > 300))]
    if not hits:
        return "fapt iXBRL negăsit"
    for h in hits:
        tol = max(1.0, 10 ** (-int(h["decimals"])) / 2 if h["decimals"].lstrip("-").isdigit() else 1.0)
        if abs(h["value"] - value) <= tol:
            return "iXBRL: potrivire"
        if abs(abs(h["value"]) - abs(value)) <= tol:
            return "iXBRL: potrivire în valoare absolută (semn diferit)"
    return "iXBRL: nepotrivire (" + ", ".join(f"{h['value'] / 1e6:,.0f}" for h in hits[:3]) + ")"


def text_rows(soup: BeautifulSoup) -> list[tuple[str, list[float]]]:
    """(label, numeric cells) for every table row of the document."""
    rows = []
    for tr in soup.find_all("tr"):
        cells = [c.get_text(" ", strip=True) for c in tr.find_all(["td", "th"])]
        cells = [c for c in cells if c not in ("", "$", ")", "%")]
        if not cells:
            continue
        label = re.sub(r"\s+", " ", cells[0]).strip().lower()
        nums = []
        for c in cells[1:]:
            c2 = "".join(ch for ch in c if ch not in NBSP).replace("$", "").strip()
            neg = c2.startswith("(")
            c2 = c2.strip("()").replace(",", "")
            if re.fullmatch(r"-?\d+(\.\d+)?", c2):
                nums.append(-float(c2) if neg else float(c2))
        if nums:
            rows.append((label, nums))
    return rows


def text_check_us(rows: list[tuple[str, list[float]]], pattern: str, value_m: float) -> tuple[str, str]:
    """Find rows whose label matches; compare the first numeric cell (current year column)."""
    rx = re.compile(r"^" + pattern + r":?$", re.I)
    matched = [r for r in rows if rx.match(r[0])]
    if not matched:
        return "nu am putut verifica automat", "eticheta de rând nu a fost găsită în document"
    firsts = [r[1][0] for r in matched]
    if any(abs(f - value_m) <= 0.5 for f in firsts):
        return "potrivire", f"rând '{matched[0][0]}', prima coloană {value_m:,.0f}"
    if any(abs(-f - value_m) <= 0.5 for f in firsts):
        # cash outflows are shown in parentheses; the taxonomy element is a positive payment
        return "potrivire (semn de prezentare)", f"rând '{matched[0][0]}' afișează ({value_m:,.0f}); elementul XBRL este o plată pozitivă"
    if any(abs(n - value_m) <= 0.5 for r in matched for n in r[1]):
        return "potrivire (altă coloană)", "valoarea apare pe rând, dar nu în prima coloană numerică"
    return "nepotrivire", "valori găsite: " + ", ".join(f"{f:,.0f}" for f in firsts[:4])


def text_check_esef(text: str, value: float, scale: int, lang: str, decimals: int) -> tuple[str, str]:
    """Search the displayed number (millions, local formatting) in the report text."""
    shown = value / 10 ** scale
    if lang == "ro":
        s = f"{shown:,.2f}"                       # 61,344.44
        candidates = [s.replace(",", "X").replace(".", ",").replace("X", ".")]  # 61.344,44
    else:
        s = f"{abs(shown):,.0f}"
        candidates = [s.replace(",", " "), s, s.replace(",", ".")]  # 84 683 / 84,683 / 84.683
    for c in candidates:
        rx = re.compile(r"(?<![\d.,])" + re.escape(c).replace(r"\ ", r"[\s]") + r"(?![\d])")
        if rx.search(text):
            return "potrivire", f"'{c}' găsit în textul raportului"
    return "nepotrivire", "numărul afișat nu a fost găsit: " + " / ".join(candidates)


def main() -> int:
    annual = {}
    for name in ("annual_us.csv", "annual_eu.csv"):
        for r in common.read_csv(common.OUT_DIR / name):
            annual[(r["entity"], int(r["fiscal_year"]), r["concept"])] = r
    L = ["# Reconcilierea cu rapoartele primare\n",
         f"Generat {common.now_iso()} de `spike/reconcile.py`. Pentru SUA: cel mai recent 10-K (documentul principal HTML) pentru exercițiul analizat; "
         "metoda text caută rândul din situația financiară și compară prima coloană numerică (anul curent); verificarea iXBRL compară faptul inline din același document, "
         "cu context fără dimensiuni, pentru aceeași perioadă. Pentru ESEF raportul XHTML este chiar raportul anual: se caută numărul afișat (format local) în text și se verifică faptul iXBRL. "
         "Rezultate posibile: potrivire, nepotrivire (cu ambele valori) sau nu am putut verifica automat (cu motivul).\n"]
    totals = {"potrivire": 0, "nepotrivire": 0, "neverificat": 0}
    custom_summary = []
    for ent, doc in DOCS.items():
        path = common.fetch(doc["url"], common.DATA_DIR / doc["path"], headers=doc["headers"], timeout=300)
        raw = path.read_text(encoding="utf-8", errors="replace")
        contexts, facts = load_ixbrl(raw)
        custom = sorted({f["name"] for f in facts if not f["dim"] and f["end"] == doc["end"]
                         and not f["name"].split(":")[0] in ("us-gaap", "dei", "srt", "ifrs-full", "ecd", "country", "stpr", "currency", "exch", "naics", "sic")})
        custom_summary.append((ent, len(custom), custom[:6]))
        L.append(f"## {ent}: FY{doc['fy']} (document {doc['accession']})\n")
        L.append(f"Sursă: {doc['url']} (sha256 {common.sha256_of(path)[:16]}..., {path.stat().st_size:,} octeți). "
                 f"Contexte iXBRL: {len(contexts)}; fapte numerice inline: {len(facts)}; etichete proprii ale emitentului cu context fără dimensiuni la data bilanțului: {len(custom)}.\n")
        L.append("| Concept | Valoare extrasă (mil.) | Rezultat text | Detaliu | Verificare iXBRL |")
        L.append("|---|---|---|---|---|")
        if ent in LABELS:
            soup = BeautifulSoup(raw, "lxml")
            rows = text_rows(soup)
            checks = LABELS[ent].items()
        else:
            text = html.unescape(re.sub(r"<[^>]+>", " ", raw))
            text = re.sub(r"[   ]", " ", text)
            checks = [(c, None) for c in ESEF_CHECK]
        for concept, pattern in checks:
            row = annual.get((ent, doc["fy"], concept))
            if not row or row["value"] == "" or row["status"] == "missing":
                L.append(f"| {concept} | lipsă | nu am putut verifica automat | concept lipsă în extracție | n/a |")
                totals["neverificat"] += 1
                continue
            value = float(row["value"])
            tags = row["source_concepts"].split(";")
            instant = concept in ("cash", "equity", "ppe_net", "goodwill", "intangibles", "current_assets", "current_liabilities")
            ix = ixbrl_check(facts, tags, doc["end"], instant, value) if len(tags) == 1 else "n/a (valoare compusă din mai multe etichete)"
            if pattern is not None:
                res, det = text_check_us(rows, pattern, value / 10 ** doc["scale"])
            else:
                res, det = text_check_esef(text, value, doc["scale"], doc["lang"], int(row.get("decimals") or -6))
            key = "potrivire" if res.startswith("potrivire") else ("nepotrivire" if res == "nepotrivire" else "neverificat")
            totals[key] += 1
            L.append(f"| {concept} ({tags[0].split(':')[-1][:38]}{'...' if len(tags[0].split(':')[-1]) > 38 else ''}) | {value / 1e6:,.2f} | {res} | {det} | {ix} |")
        L.append("")
    L.append("## Sumar\n")
    L.append(f"Potriviri: {totals['potrivire']}; nepotriviri: {totals['nepotrivire']}; neverificate automat: {totals['neverificat']}.\n")
    L.append("Etichete proprii ale emitenților (prefix propriu, context fără dimensiuni, la data bilanțului) găsite în documentele primare, pe care companyfacts nu le expune:\n")
    for ent, n, sample in custom_summary:
        L.append(f"- {ent}: {n} etichete proprii; exemple: {', '.join(sample) if sample else 'niciuna'}")
    L.append("")
    (common.OUT_DIR / "reconciliation.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(totals)
    return 0


if __name__ == "__main__":
    sys.exit(main())
